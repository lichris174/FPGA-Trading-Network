"""Generate the Verilog header of ITCH message layouts from spec.py.

    python -m golden.itch.gen_verilog            # writes rtl/itch/itch_spec.vh
    python -m golden.itch.gen_verilog --check    # exit 1 if the file is out of date

spec.py is the one place byte offsets are written down; the Verilog
gets them from this generated file instead of a hand copy, so the two
can't drift apart (see docs/decisions.md). tests/golden/test_gen_verilog.py
fails if the committed header doesn't match.

Names use the message name, not the type code, because Verilog would
see "h" (operational halt) and "H" (trading action) as different but
easy-to-confuse identifiers:

    ITCH_ADD_ORDER_TYPE       8'h41   type byte ("A")
    ITCH_ADD_ORDER_LEN        36      message length without the 2-byte prefix
    ITCH_ADD_ORDER_PRICE_OFF  32      byte offset of a field
    ITCH_ADD_ORDER_PRICE_SIZE 4       field size in bytes

No include guard: each module that includes it gets its own copy of
the localparams.
"""

import argparse
import sys
from pathlib import Path

from .spec import HEADER, MESSAGES

OUT = Path(__file__).resolve().parents[2] / "rtl" / "itch" / "itch_spec.vh"


def render():
    lines = [
        "// Generated by `python -m golden.itch.gen_verilog` from golden/itch/spec.py.",
        "// Do not edit by hand: change spec.py and regenerate.",
        "",
        "// Common header, the same in every message.",
    ]
    for f in HEADER:
        lines.append(f"localparam ITCH_HDR_{f.name.upper()}_OFF = {f.offset};")
        lines.append(f"localparam ITCH_HDR_{f.name.upper()}_SIZE = {f.size};")
    for m in MESSAGES.values():
        p = f"ITCH_{m.name.upper()}"
        lines += ["", f"// {m.code}: {m.name}"]
        lines.append(f"localparam [7:0] {p}_TYPE = 8'h{ord(m.code):02X};")
        lines.append(f"localparam {p}_LEN = {m.length};")
        for f in m.fields[len(HEADER):]:
            lines.append(f"localparam {p}_{f.name.upper()}_OFF = {f.offset};")
            lines.append(f"localparam {p}_{f.name.upper()}_SIZE = {f.size};")
    return "\n".join(lines) + "\n"


def main(argv=None):
    p = argparse.ArgumentParser(prog="python -m golden.itch.gen_verilog")
    p.add_argument("--check", action="store_true", help="only check that the file is up to date")
    a = p.parse_args(argv)
    text = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is out of date, run python -m golden.itch.gen_verilog", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
